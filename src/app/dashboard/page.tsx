"use client";

import React, { useEffect, useState } from "react";
import { createClient } from "@/lib/supabase/client";
import { useRouter } from "next/navigation";
import Navbar from "@/components/Navbar";
import Footer from "@/components/Footer";
import Link from "next/link";

export default function DashboardPage() {
  const [user, setUser] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const router = useRouter();
  const supabase = createClient();

  useEffect(() => {
    async function checkUser() {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) {
        router.push("/auth/login");
      } else {
        setUser(user);
      }
      setLoading(false);
    }
    checkUser();
  }, [router, supabase]);

  const handleSignOut = async () => {
    await supabase.auth.signOut();
    router.push("/");
    router.refresh();
  };

  if (loading) {
    return (
      <div className="min-h-screen flex flex-col bg-luxury-cream text-luxury-charcoal">
        <Navbar />
        <div className="flex-1 flex items-center justify-center">
          <p className="text-xs uppercase tracking-widest text-gray-500">Loading Dashboard...</p>
        </div>
        <Footer />
      </div>
    );
  }

  return (
    <div className="min-h-screen flex flex-col bg-luxury-cream text-luxury-charcoal">
      <Navbar />

      <div className="flex-1 max-w-7xl mx-auto px-6 lg:px-12 py-16">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-6 border-b border-luxury-border pb-8 mb-12">
          <div>
            <span className="text-xs uppercase font-bold tracking-[0.25em] text-luxury-gold">Client Portal</span>
            <h1 className="text-3xl font-bold font-serif text-luxury-charcoal mt-1">Brand Dashboard</h1>
            <p className="text-xs text-gray-500 mt-1">{user?.email}</p>
          </div>
          <button
            onClick={handleSignOut}
            className="bg-transparent border border-luxury-charcoal text-luxury-charcoal hover:bg-luxury-charcoal hover:text-white px-6 py-2.5 text-xs font-bold tracking-widest uppercase transition-all rounded-sm"
          >
            Sign Out
          </button>
        </div>

        {/* Dashboard Grid */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-8 mb-12">
          <div className="bg-white p-6 rounded-lg border border-luxury-border shadow-sm space-y-3">
            <span className="text-2xl text-luxury-gold">📦</span>
            <h3 className="font-serif font-bold text-lg text-luxury-charcoal">Active Orders</h3>
            <p className="text-xs text-gray-500 font-light">No active orders yet. Calculate a price or order via WhatsApp to start production.</p>
            <div className="pt-2">
              <Link href="/#calculator" className="text-xs font-bold uppercase tracking-widest text-luxury-gold hover:underline">
                New Price Calculation →
              </Link>
            </div>
          </div>

          <div className="bg-white p-6 rounded-lg border border-luxury-border shadow-sm space-y-3">
            <span className="text-2xl text-luxury-gold">🎨</span>
            <h3 className="font-serif font-bold text-lg text-luxury-charcoal">Artwork Proofs</h3>
            <p className="text-xs text-gray-500 font-light">Review woven and printed proof approvals generated by our Tirupur technicians.</p>
            <div className="pt-2">
              <span className="text-xs text-gray-400 uppercase tracking-widest font-semibold">No Pending Proofs</span>
            </div>
          </div>

          <div className="bg-white p-6 rounded-lg border border-luxury-border shadow-sm space-y-3">
            <span className="text-2xl text-luxury-gold">💬</span>
            <h3 className="font-serif font-bold text-lg text-luxury-charcoal">Direct Support</h3>
            <p className="text-xs text-gray-500 font-light">Chat directly with our manufacturing desk for custom vectors and rush orders.</p>
            <div className="pt-2">
              <a
                href="https://wa.me/918608847513?text=Hi%20Vector%20Labels%20Team%2C%20I%20am%20logged%20into%20my%20dashboard%20and%20need%20assistance."
                target="_blank"
                rel="noopener noreferrer"
                className="text-xs font-bold uppercase tracking-widest text-luxury-gold hover:underline"
              >
                Open WhatsApp Chat →
              </a>
            </div>
          </div>
        </div>
      </div>

      <Footer />
    </div>
  );
}
